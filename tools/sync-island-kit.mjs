// Copies the procedural island kit from spike/procedural into the app.
//   kit:     core.js, surfaces.js, world.js, island.js, scatter.js, parts/*.js -> src/world/island/kit/
//   samples: scenes/islands/*.json (except names starting with "_")       -> src/world/island/samples/
// `three/addons/` imports become `three/examples/jsm/` so Metro resolves them.
// Hand-written files in kit/ (world.d.ts) are kept; copied .js files and samples are replaced.
// Usage: npm run sync:island
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const source = path.join(root, "spike/procedural");
const kitDir = path.join(root, "src/world/island/kit");
const samplesDir = path.join(root, "src/world/island/samples");
const kitFiles = ["core.js", "surfaces.js", "world.js", "island.js", "scatter.js"];
const header =
  "// @ts-nocheck\n// Generated by tools/sync-island-kit.mjs from spike/procedural. Do not edit here.\n";

function removeMatching(dir, test) {
  if (!fs.existsSync(dir)) return;
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) removeMatching(full, test);
    else if (test(entry.name)) fs.rmSync(full);
  }
}

function copyKitFile(relative) {
  const from = path.join(source, relative);
  if (!fs.existsSync(from)) {
    console.warn(`missing ${path.relative(root, from)}`);
    return false;
  }
  const code = fs.readFileSync(from, "utf8").replaceAll("three/addons/", "three/examples/jsm/");
  const to = path.join(kitDir, relative);
  fs.mkdirSync(path.dirname(to), { recursive: true });
  fs.writeFileSync(to, header + code);
  return true;
}

removeMatching(kitDir, (name) => name.endsWith(".js"));
removeMatching(samplesDir, (name) => name.endsWith(".json"));
fs.mkdirSync(kitDir, { recursive: true });
fs.mkdirSync(samplesDir, { recursive: true });

const parts = fs
  .readdirSync(path.join(source, "parts"))
  .filter((name) => name.endsWith(".js"))
  .sort()
  .map((name) => `parts/${name}`);
const copied = [...kitFiles, ...parts].filter(copyKitFile);

const islands = path.join(source, "scenes/islands");
const samples = fs.existsSync(islands)
  ? fs.readdirSync(islands).filter((name) => name.endsWith(".json") && !name.startsWith("_")).sort()
  : [];
const synced = samples.filter((name) => {
  try {
    const json = JSON.parse(fs.readFileSync(path.join(islands, name), "utf8"));
    fs.writeFileSync(path.join(samplesDir, name), JSON.stringify(json, null, 2) + "\n");
    return true;
  } catch (error) {
    console.warn(`skipping ${name}: ${error.message}`);
    return false;
  }
});

console.log(`kit: ${copied.length} files -> ${path.relative(root, kitDir)}`);
console.log(`samples: ${synced.length ? synced.join(", ") : "none"} -> ${path.relative(root, samplesDir)}`);
